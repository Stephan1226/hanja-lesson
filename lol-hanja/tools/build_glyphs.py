#!/usr/bin/env python3
"""Inline the ancient-script SVGs (Wikimedia Commons) into js/glyphs.js.

The deck is meant to be opened straight from disk (file://), where fetch() and
CSS mask-image are blocked, so the glyph outlines are baked into a script file.
That lets deck.js put them in the DOM as inline SVG and animate the "carving".

Usage: python3 tools/build_glyphs.py
"""
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "glyphs"
OUT = ROOT / "js" / "glyphs.js"
SVG_NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG_NS)


def clean(el):
    for child in list(el):
        tag = child.tag
        local = tag.split("}")[-1]
        if not tag.startswith("{%s}" % SVG_NS) or local in ("metadata", "defs", "title", "desc"):
            el.remove(child)
            continue
        clean(child)
    for k in list(el.attrib):
        if k.startswith("{") or k == "id":
            del el.attrib[k]


def recolor(markup):
    # Black outlines become currentColor; the grey parts some files use for
    # reconstructed strokes become a faint version of the same colour.
    markup = re.sub(r"fill:#(?:000000|010101|000)\b", "fill:currentColor", markup)
    markup = re.sub(r'fill="#(?:000000|010101|000)"', 'fill="currentColor"', markup)
    markup = re.sub(r'style="fill:#bababa', 'class="faint" style="fill:currentColor', markup)
    return markup


def inner(path):
    root = ET.parse(path).getroot()
    clean(root)
    vb = root.get("viewBox") or "0 0 %s %s" % (root.get("width", "300"), root.get("height", "300"))
    body = "".join(ET.tostring(c, encoding="unicode") for c in root)
    body = body.replace(' xmlns="%s"' % SVG_NS, "")
    body = re.sub(r"\s+", " ", body)
    return vb, recolor(body)


def knot(x, y, h):
    # One 幺 (silk-thread skein) as it appears in oracle bone forms: a cord
    # twisted into two loops, with loose ends above and below. Drawn as a
    # stroke and marked .st so the CSS keeps its width.
    m, t, b = y + h / 2, y, y + h
    w = h * 0.3
    return (
        f'<path class="st" d="M{x - 6},{t - 24} L{x},{t} '
        f"C{x + w},{t + 10} {x + w * 0.7},{m - 10} {x},{m} C{x - w * 0.7},{m + 10} {x - w},{b - 10} {x},{b} "
        f"M{x},{t} C{x - w},{t + 10} {x - w * 0.7},{m - 10} {x},{m} C{x + w * 0.7},{m + 10} {x + w},{b - 10} {x},{b} "
        f'L{x + 6},{b + 24}" fill="none" stroke="currentColor" stroke-width="10" stroke-linecap="round" stroke-linejoin="round"/>'
    )


def main():
    glyphs = {}
    for f in sorted(SRC.glob("*.svg")):
        vb, body = inner(f)
        glyphs[f.stem] = {"vb": vb, "svg": body}

    # 幽 has no oracle-bone drawing on Commons. Its oracle/bronze form is two
    # 幺 skeins above 火 (Wiktionary: "fire with two 幺 ... meaning faint fire"),
    # so we compose that diagram from the real 火 / 山 oracle outlines and
    # label it as a reconstruction in the deck.
    threads = knot(102, 34, 96) + knot(198, 34, 96)
    for base, key in (("火-oracle", "幽-recon"), ("山-oracle", "幽-recon-mountain")):
        g = glyphs[base]["svg"]
        glyphs[key] = {
            "vb": "0 0 300 300",
            "svg": threads + f'<g transform="translate(75 150) scale(.5)">{g}</g>',
        }

    OUT.write_text(
        "// Generated by tools/build_glyphs.py from assets/glyphs/*.svg (Wikimedia Commons). Do not edit.\n"
        "window.GLYPHS = " + json.dumps(glyphs, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"{len(glyphs)} glyphs -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
